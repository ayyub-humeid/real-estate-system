def add_text(text='', style=None, bold_prefix=None, keep=False, color=None, size=None):
    p = doc.add_paragraph(style=style)
    set_rtl_paragraph(p)
    if bold_prefix and text.startswith(bold_prefix):
        r = p.add_run(bold_prefix)
        r.bold = True
        set_rtl_run(r)
        r2 = p.add_run(text[len(bold_prefix):])
        set_rtl_run(r2)
    else:
        r = p.add_run(text)
        set_rtl_run(r)
    if color:
        for r in p.runs:
            r.font.color.rgb = RGBColor.from_string(color)
    if size:
        for r in p.runs:
            r.font.size = Pt(size)
    if keep:
        set_keep_with_next(p)
    return p


